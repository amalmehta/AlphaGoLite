"""Table 2: the same search on three runtimes (bench/result_*.json, bench/export_parity.json).
The fastest median is bolded automatically."""
import json
import statistics

import common as c

par = json.loads((c.BENCH / "export_parity.json").read_text())


def sci(x):
    m, e = f"{x:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


specs = [("python", "PyTorch", "--"),
         ("swift", "Core ML", sci(par["coreml_max_abs_diff"])),
         ("browser", "ONNX (web)", sci(par["onnx_max_abs_diff"]))]
res = {k: json.loads((c.BENCH / f"result_{k}.json").read_text()) for k, _, _ in specs}
ref = res["python"]["cases"]
med = {k: statistics.median(x["ms"] for x in res[k]["cases"]) for k, _, _ in specs}
best = min(med, key=med.get)
lines = []
for k, name, diff in specs:
    same = sum(x["visits"] == r["visits"] for x, r in zip(res[k]["cases"], ref))
    ms = f"{med[k]:.0f}"
    sps = f"{res[k]['sims'] / med[k] * 1000:.0f}"
    if k == best:
        ms, sps = f"\\textbf{{{ms}}}", f"\\textbf{{{sps}}}"
    lines.append(f"{name} & {ms} & {sps} & {same}/{len(ref)} & {diff} \\\\")
c.write("generated/tables/platform.tex", f"""% generated by figures_scripts/platform_table.py
\\begin{{tabular}}{{@{{}}lrrrr@{{}}}}
\\toprule
Runtime & ms & sims/s & Same & Max $|\\Delta|$ \\\\
\\midrule
{chr(10).join(lines)}
\\bottomrule
\\end{{tabular}}
""")
