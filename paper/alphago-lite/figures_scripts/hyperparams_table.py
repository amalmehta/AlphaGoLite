"""Table 1: settings, read from the trainer's code and the run's config (never typed by hand)."""
import inspect
import sys

import common as c

sys.path.insert(0, str(c.HERE.parents[2] / "trainer"))
from alphago_lite import go, mcts, net, selfplay  # noqa: E402

cfg = c.load("metrics.json")["config"]
noise = inspect.signature(mcts.Node.add_noise).parameters
rows = [
    ("Board, komi, move cap", f"{go.N}$\\times${go.N}, {go.KOMI}, {go.MAX_MOVES}"),
    ("Input planes", str(go.NUM_PLANES)),
    ("Residual blocks $\\times$ channels", f"{net.BLOCKS} $\\times$ {net.CHANNELS}"),
    ("$c_{\\mathrm{puct}}$, FPU reduction", f"{mcts.C_PUCT}, {mcts.FPU_REDUCTION}"),
    ("Dirichlet $\\alpha$, $\\varepsilon$", f"{noise['alpha'].default}, {noise['eps'].default}"),
    ("Sims: full / fast search", f"{cfg['sims']} / {cfg['sims'] // selfplay.FAST_SIMS_DIVISOR}"),
    ("Full-search probability", str(selfplay.FULL_SEARCH_PROB)),
    ("Temperature-1 moves", str(selfplay.TEMP_MOVES)),
    ("Games / generation, workers", f"{cfg['games_per_gen']}, {cfg['workers']}"),
    ("Batch, learning rate (AdamW)", f"{cfg['batch']}, {cfg['lr']}"),
    ("Replay window (positions)", f"{cfg['window']:,}"),
    ("Chained eval: games, sims", f"{cfg['eval_games']}, {cfg['eval_sims']}"),
]
body = "\n".join(f"{k} & {v} \\\\" for k, v in rows)
c.write("generated/tables/hyperparams.tex", f"""% generated by figures_scripts/hyperparams_table.py
\\begin{{tabular}}{{@{{}}ll@{{}}}}
\\toprule
Setting & Value \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
""")
